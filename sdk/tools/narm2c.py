#!/usr/bin/env python3
"""
narm2c.py <module.narm> <prefix> <embed 0|1>  ->  C source on stdout

Puts a native module into the 68k program, for any 68k compiler (VBCC, GCC):

    const unsigned long <prefix>_narm_build_id;     CRC32 of the module (zlib)
    const unsigned long <prefix>_narm_image_size;   0 when not embedded
    const unsigned char <prefix>_narm_image[];

NC_MODULE() (nativecall/kernel.h) refers to these: nc_open() loads the embedded copy, and a
.narm file next to the program is only accepted when its CRC32 matches the build ID.
"""

import sys
import zlib


def main():
    path, prefix, embed = sys.argv[1], sys.argv[2], sys.argv[3] == "1"
    data = open(path, "rb").read()
    crc = zlib.crc32(data) & 0xFFFFFFFF
    out = sys.stdout

    out.write("/* Generated by narm2c.py from %s - do not edit */\n\n" % path.split("/")[-1])
    out.write("const unsigned long %s_narm_build_id = 0x%08xUL;\n" % (prefix, crc))
    if not embed:
        out.write("const unsigned long %s_narm_image_size = 0;\n" % prefix)
        out.write("const unsigned char %s_narm_image[4] = { 0 };\n" % prefix)
        return
    out.write("const unsigned long %s_narm_image_size = %d;\n" % (prefix, len(data)))
    out.write("const unsigned char %s_narm_image[%d] =\n{\n" % (prefix, len(data)))
    for i in range(0, len(data), 16):
        out.write("    " + ", ".join("0x%02x" % b for b in data[i:i + 16]) + ",\n")
    out.write("};\n")


if __name__ == "__main__":
    main()
