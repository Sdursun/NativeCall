#!/usr/bin/env python3
"""
narm2c.py <module.narm> <prefix> <embed 0|1> [<module.nx64>]  ->  C source on stdout

Puts a native module into the 68k program, for any 68k compiler (VBCC, GCC):

    const unsigned long <prefix>_narm_build_id;     CRC32 of the module (zlib)
    const unsigned long <prefix>_narm_image_size;   0 when not embedded
    const unsigned char <prefix>_narm_image[];
    const unsigned long <prefix>_nx64_image_size;   0 without a .nx64
    const unsigned char <prefix>_nx64_image[];      the x64 module for WinUAE (sdk/x64)

NC_MODULE() (nativecall/kernel.h) refers to these: nc_open() loads the embedded copy (under
WinUAE's x64 backend the .nx64), and a .narm file next to the program is only accepted when its
CRC32 matches the build ID.
"""

import struct
import sys
import zlib


def write_array(out, name, data):
    out.write("const unsigned long %s_size = %d;\n" % (name, len(data)))
    out.write("const unsigned char %s[%d] =\n{\n" % (name, len(data)))
    for i in range(0, len(data), 16):
        out.write("    " + ", ".join("0x%02x" % b for b in data[i:i + 16]) + ",\n")
    out.write("};\n")


def write_empty(out, name):
    out.write("const unsigned long %s_size = 0;\n" % name)
    out.write("const unsigned char %s[4] = { 0 };\n" % name)


def main():
    path, prefix, embed = sys.argv[1], sys.argv[2], sys.argv[3] == "1"
    nx64 = sys.argv[4] if len(sys.argv) > 4 else None
    data = open(path, "rb").read()
    crc = zlib.crc32(data) & 0xFFFFFFFF
    out = sys.stdout

    out.write("/* Generated by narm2c.py from %s - do not edit */\n\n" % path.split("/")[-1])
    out.write("const unsigned long %s_narm_build_id = 0x%08xUL;\n" % (prefix, crc))
    if embed:
        write_array(out, prefix + "_narm_image", data)
    else:
        write_empty(out, prefix + "_narm_image")
    if nx64:
        x = open(nx64, "rb").read()
        # the .nx64 belongs to this .narm (tools/mknx64.py: 'NX64', version, CRC32 of the .narm)
        if len(x) < 32 or x[0:4] != b"NX64" or struct.unpack(">I", x[8:12])[0] != crc:
            sys.exit("narm2c.py: %s was not built from %s" % (nx64, path))
        write_array(out, prefix + "_nx64_image", x)
    else:
        write_empty(out, prefix + "_nx64_image")


if __name__ == "__main__":
    main()
